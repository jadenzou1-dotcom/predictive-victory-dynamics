"""Build the README charts from the CSVs in data/.

Writes a light and a dark PNG of each to charts/:
  points_by_round_{light,dark}.png   cumulative prediction score per account
  lookahead_{light,dark}.png         Brier score of each predictor, ordered by look-ahead bias

(The full model-vs-crowd record is a table, generated by make_results.py.)

Usage: python scripts/make_charts.py
"""
import re
import sys
from collections import OrderedDict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from pvd import RAW, ROOT                                                 # noqa: E402
from pvd.evaluate import PREDICTORS, SCORES, load, matches, scored        # noqa: E402

OUT = ROOT / "charts"

# Palette: validated categorical slots (blue, orange) plus neutral ink.
THEMES = {
    "light": dict(surface="#fcfcfb", ink="#0b0b0b", ink2="#52514e", grid="#e4e3df",
                  shado="#2a78d6", dino="#eb6834", crowd="#7a7975"),
    "dark": dict(surface="#1a1a19", ink="#f0efec", ink2="#c3c2b7", grid="#33322f",
                 shado="#3987e5", dino="#d95926", crowd="#8f8e88"),
}


board = load(RAW / "leaderboard.csv")
best_friend = max(int(r["score"]) for r in board if r["is_ours"] != "yes")

# ---- cumulative points by round ---------------------------------------------
rounds = OrderedDict()
tot = {"Shadow": 0, "Dino": 0}
for m in matches:
    for acct, pts in re.findall(r"(Shadow|Dino) (\d+)", m["score_earned"]):
        tot[acct] += int(pts)
    rounds[m["round"]] = dict(tot)
labels = list(rounds)
shado = [rounds[r]["Shadow"] for r in labels]
dino = [rounds[r]["Dino"] for r in labels]
skipped = {m["round"] for m in matches if m["pick"].startswith("none")}

def style(ax, t):
    ax.set_facecolor(t["surface"])
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(t["grid"])
    ax.tick_params(colors=t["ink2"], length=0, labelsize=9)
    ax.grid(axis="y", color=t["grid"], linewidth=0.8)
    ax.set_axisbelow(True)


def points_chart(mode):
    t = THEMES[mode]
    fig, ax = plt.subplots(figsize=(8, 4.2), dpi=160, facecolor=t["surface"])
    style(ax, t)
    x = range(len(labels))
    ax.hlines(best_friend, -0.3, len(labels) - 1, color=t["crowd"], linewidth=1.2, linestyle=(0, (4, 3)))
    ax.annotate(f"Best friend\n{best_friend:,}", (len(labels) - 1, best_friend), xytext=(8, 0),
                textcoords="offset points", va="center", fontsize=9, color=t["ink2"])
    for ys, c, name in ((dino, t["dino"], "Dino · max EV"), (shado, t["shado"], "Shado · risk-adjusted")):
        ax.plot(x, ys, color=c, linewidth=2, marker="o", markersize=5,
                markeredgecolor=t["surface"], markeredgewidth=1.5, zorder=3)
        ax.annotate(f"{name}\n{ys[-1]:,}", (len(labels) - 1, ys[-1]), xytext=(8, 0),
                    textcoords="offset points", va="center", fontsize=9, color=t["ink"])
    for i, r in enumerate(labels):
        if r in skipped:
            ax.text(i, -6500, "no bets", ha="center", fontsize=7.5, color=t["ink2"], style="italic")
    ax.set_xticks(list(x), labels)
    ax.set_ylim(0, 90000)
    ax.set_xlim(-0.3, len(labels) - 1 + 1.9)
    ax.yaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda v, _: f"{v / 1000:.0f}k"))
    ax.set_title("Cumulative prediction score by round", loc="left", color=t["ink"], fontsize=12, pad=12)
    fig.tight_layout()
    fig.savefig(OUT / f"points_by_round_{mode}.png", facecolor=t["surface"])
    plt.close(fig)


# ---- look-ahead bias vs forecast quality ------------------------------------
LEAK = {"live": "no look-ahead", "swf": "minimal look-ahead", "wf": "structural look-ahead",
        "loo": "structural + parameter", "crowd": "market baseline"}


def lookahead_chart(mode):
    """One bar per predictor (Brier, lower is better), least to most leakage, crowd last.
    Model rows share one hue; the crowd is the neutral baseline. Correct calls are direct labels."""
    t = THEMES[mode]
    rows = [(k, label.strip("*"), *SCORES[k]) for k, label, _, _ in PREDICTORS]
    fig, ax = plt.subplots(figsize=(8, 3.6), dpi=160, facecolor=t["surface"])
    style(ax, t)
    ax.grid(axis="y", visible=False)
    ax.grid(axis="x", color=t["grid"], linewidth=0.8)
    ax.spines["bottom"].set_visible(False)
    y = list(range(len(rows)))[::-1]
    for yi, (k, label, right, brier) in zip(y, rows):
        c = t["crowd"] if k == "crowd" else t["shado"]
        ax.barh(yi, brier, height=0.56, color=c, alpha=1.0 if k in ("live", "crowd") else 0.55)
        ax.text(brier + 0.006, yi, f"{brier:.3f}  ·  {right}/{len(scored)} correct",
                va="center", fontsize=9, color=t["ink"], zorder=4,
                bbox=dict(boxstyle="square,pad=0.15", facecolor=t["surface"], edgecolor="none"))
    ax.set_yticks(y, [f"{label}\n{LEAK[k]}" for k, label, *_ in rows], fontsize=9)
    for tick in ax.get_yticklabels():
        tick.set_color(t["ink"])
    ax.axhline(0.5, color=t["grid"], linewidth=0.8)
    ax.axvline(0.25, color=t["ink2"], linewidth=1, linestyle=(0, (4, 3)))
    ax.text(0.254, len(rows) - 0.42, "0.25 = always say 50%", ha="left", fontsize=8, color=t["ink2"])
    ax.set_xlim(0, 0.42)
    ax.set_ylim(-0.6, len(rows) - 0.3)
    ax.set_title("Brier score (lower is better). More look-ahead flatters the backtest",
                 loc="left", color=t["ink"], fontsize=11, pad=10)
    fig.tight_layout()
    fig.savefig(OUT / f"lookahead_{mode}.png", facecolor=t["surface"])
    plt.close(fig)


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    for mode in THEMES:
        points_chart(mode)
        lookahead_chart(mode)
    print("final:", {"Shado": shado[-1], "Dino": dino[-1]})
